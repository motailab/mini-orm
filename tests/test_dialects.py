"""Tests for the SQL of each dialect. These tests do not use a database server."""

import pytest

from mini_orm import (
    Count,
    ModelDefinitionError,
    MySQLDialect,
    PostgreSQLDialect,
    Query,
    SQLiteDialect,
    StringField,
    create_table_sql,
)
from mini_orm.compiler import compile_insert
from mini_orm.dialects import dialect_for_url
from mini_orm.schema import Column

from .example_models import Author, Book

SQLITE, POSTGRESQL, MYSQL = SQLiteDialect(), PostgreSQLDialect(), MySQLDialect()


def test_the_url_selects_the_dialect():
    assert dialect_for_url(":memory:").name == "sqlite"
    assert dialect_for_url("shop.db").name == "sqlite"
    assert dialect_for_url("sqlite:///shop.db").name == "sqlite"
    assert dialect_for_url("postgresql://user:secret@localhost:5432/shop").name == "postgresql"
    assert dialect_for_url("postgres://localhost/shop").name == "postgresql"
    assert dialect_for_url("mysql://user:secret@localhost:3306/shop").name == "mysql"


def test_a_query_gets_the_placeholders_and_the_quotes_of_the_dialect():
    query = Query(Author).where(Author.name == "Alice").order_by("-id").limit(5)
    assert query.to_sql(POSTGRESQL) == (
        'SELECT "authors"."id", "authors"."name", "authors"."email" FROM "authors" '
        'WHERE "authors"."name" = %s ORDER BY "authors"."id" DESC LIMIT %s',
        ["Alice", 5],
    )
    assert query.to_sql(MYSQL) == (
        "SELECT `authors`.`id`, `authors`.`name`, `authors`.`email` FROM `authors` "
        "WHERE `authors`.`name` = %s ORDER BY `authors`.`id` DESC LIMIT %s",
        ["Alice", 5],
    )


@pytest.mark.parametrize(
    ("dialect", "expected"),
    [
        (SQLITE, "LIMIT -1 OFFSET ?"),
        (POSTGRESQL, "OFFSET %s"),
        (MYSQL, "LIMIT 18446744073709551615 OFFSET %s"),
    ],
)
def test_offset_without_limit(dialect, expected):
    text, params = Query(Author).offset(10).to_sql(dialect)
    assert text.endswith(f"FROM {dialect.quote_name('authors')} {expected}")
    assert params == [10]


def test_aggregates_and_aliases():
    text, params = (
        Query(Book).group_by(Book.author).having(Count() > 1).values(Book.author, n=Count()).to_sql(MYSQL)
    )
    assert text == (
        "SELECT `books`.`author_id` AS `author`, COUNT(*) AS `n` FROM `books` "
        "GROUP BY `books`.`author_id` HAVING COUNT(*) > %s"
    )
    assert params == [1]


def test_insert_returns_the_new_key_on_postgresql_only():
    author = Author(name="Alice")
    assert compile_insert(author, POSTGRESQL) == (
        'INSERT INTO "authors" ("name", "email") VALUES (%s, %s) RETURNING "id"',
        ["Alice", None],
    )
    # SQLite and MySQL give the new key in cursor.lastrowid.
    assert compile_insert(author, MYSQL)[0] == "INSERT INTO `authors` (`name`, `email`) VALUES (%s, %s)"
    author.id = 7  # A key that the program gives needs no RETURNING.
    assert "RETURNING" not in compile_insert(author, POSTGRESQL)[0]


def test_insert_of_a_row_without_values():
    assert POSTGRESQL.empty_insert_sql("categories") == 'INSERT INTO "categories" DEFAULT VALUES'
    assert MYSQL.empty_insert_sql("categories") == "INSERT INTO `categories` () VALUES ()"


def test_create_table_for_postgresql():
    assert create_table_sql(Book, POSTGRESQL) == (
        'CREATE TABLE IF NOT EXISTS "books" (\n'
        '    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n'
        '    "title" TEXT NOT NULL,\n'
        '    "price" DOUBLE PRECISION,\n'
        '    "published" BOOLEAN,\n'
        '    "released_on" DATE,\n'
        '    "author_id" INTEGER,\n'
        '    CONSTRAINT "books_author_id_fkey" FOREIGN KEY ("author_id") '
        'REFERENCES "authors" ("id") ON DELETE CASCADE\n'
        ")"
    )


def test_create_table_for_mysql_names_the_unique_constraint():
    assert create_table_sql(Author, MYSQL) == (
        "CREATE TABLE IF NOT EXISTS `authors` (\n"
        "    `id` INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,\n"
        "    `name` VARCHAR(50) NOT NULL,\n"
        "    `email` VARCHAR(100),\n"
        "    CONSTRAINT `authors_email_key` UNIQUE (`email`)\n"
        ")"
    )


def test_mysql_refuses_a_unique_text_column():
    column = Column.from_field(StringField(unique=True))
    with pytest.raises(ModelDefinitionError, match="Give the StringField a max_length"):
        MYSQL.column_type(column)
    assert POSTGRESQL.column_type(column) == "TEXT"


def test_constraint_names_have_at_most_63_characters():
    long_name = "a" * 70
    assert len(POSTGRESQL.unique_name(long_name, "email")) == 63
    assert POSTGRESQL.foreign_key_name("books", "author_id") == "books_author_id_fkey"
